# Matrix key that names the vcpkg triplet, per job (the Android matrix has no vcpkg-triplet, only the cargo target).
# macOS is left out on purpose: its two caches (~1.5 GB each) pushed the repository over the 10 GB limit, and its time is
# dominated by flutter/Xcode, which a cache does not shorten. Only Windows and Android are cached.
VCPKG_TRIPLET_KEY = {"build-for-windows-flutter": "vcpkg-triplet", "build-rustdesk-android": "target"}

# Only the default branch writes the compiler cache (a release only reads it): every release is a new tag, and a cache
# saved in a tag's scope is 1.4-2.2 GB per platform that nobody can read again.
RUST_CACHE_SAVE_IF = "          save-if: ${{ github.ref == format('refs/heads/{0}', github.event.repository.default_branch) }}\n"


def split_jobs(text):
    head, _, body = text.partition("\njobs:\n")
    parts = re.split(r"(?m)^(?=  [A-Za-z0-9_-]+:\s*$)", body)
    jobs = {}
    for p in parts:
        m = re.match(r"  ([A-Za-z0-9_-]+):", p)
        if m:
            jobs[m.group(1)] = p
    return head, jobs


def fail(msg):
    sys.exit(f"make_workflow: {msg}")


def insert_stamp(job_name, text):
    """After the first checkout step of a job that compiles our code."""
    m = re.search(r"(?m)^      - (?:name: [^\n]*\n        )?uses: actions/checkout@[^\n]*\n(?:        [^\n]*\n)*\n?", text)
    if not m:
        fail(f"{job_name}: no checkout step found")
    return text[:m.end()] + ("\n" if not text[:m.end()].endswith("\n\n") else "") + STAMP + text[m.end():]


def drop_rust_cache(text):
    """The macOS job does not use the compiler cache (see VCPKG_TRIPLET_KEY)."""
    pat = re.compile(r"      - uses: Swatinem/rust-cache@\S+ # v2\n        with:\n(?:          .*\n)+\n")
    found = pat.findall(text)
    if len(found) != 1:
        fail(f"build-for-macOS: rust-cache step found {len(found)}x, wanted 1x")
    return pat.sub("", text, count=1)


def mac_ad_hoc(text):
    """Replace upstream's 'Rename rustdesk' step with: ad hoc signing (when no certificate) + rename."""
    anchor_re = re.compile(r"      - name: Rename rustdesk\n(?:        [^\n]*\n|          [^\n]*\n)+")
    m = anchor_re.search(text)
    if not m:
        fail("build-for-macOS: step 'Rename rustdesk' not found")
    new = '''      - name: Sign ad hoc and create the dmg
        # No Apple Developer ID (it costs US$ 99/year), so the app gets an ad hoc signature: Apple Silicon
        # only runs signed code and this satisfies it. Gatekeeper still warns once; the install notes of
        # the release explain "Open Anyway".
        if: env.MACOS_P12_BASE64 == null && env.UPLOAD_ARTIFACT == 'true'
        shell: bash
        run: |
          APP="./flutter/build/macos/Build/Products/Release/${RD_APP_NAME}.app"
          test -d "$APP"
          bash ./.github/scripts/sign-macos-app.sh "$APP" - ./flutter/macos/Runner/Release.entitlements
          codesign -dv "$APP" 2>&1 | grep -E "Identifier|Signature|flags" || true
          CREATE_DMG="$(readlink -f "$(command -v create-dmg)")"
          sed -i -e 's/MAXIMUM_UNMOUNTING_ATTEMPTS=3/MAXIMUM_UNMOUNTING_ATTEMPTS=7/' "$CREATE_DMG"
          rm -f ./*.dmg
          create-dmg --icon "${RD_APP_NAME}.app" 200 190 --hide-extension "${RD_APP_NAME}.app" --window-size 800 400 --app-drop-link 600 185 "${APP_LOWER}-${TAG_NAME}.dmg" "$APP"

      - name: Name the dmg like the other packages
        if: env.UPLOAD_ARTIFACT == 'true'
        shell: bash
        env:
          ARCH: ${{ matrix.job.arch }}
        run: |
          # the signed and the ad hoc paths both leave <app>-<tag>.dmg; the unsigned one created earlier
          # is already named <app>-<tag>-<arch>.dmg and is replaced here
          src="${APP_LOWER}-${TAG_NAME}.dmg"
          [ -f "$src" ] || src="${APP_LOWER}-${TAG_NAME}-${ARCH}.dmg"
          out="${APP_LOWER}-${TAG_NAME}-${ARCH}.dmg"
          [ "$src" = "$out" ] || mv "$src" "$out"
          test -f "$out"
          echo "DMG_FILE=$out" >> "$GITHUB_ENV"

'''
    return text[:m.start()] + new + text[m.end():], m.group(0)


def generate(src_text):
    head, jobs = split_jobs(src_text)
    missing = [k for k in KEEP if k not in jobs]
    if missing:
        fail(f"upstream no longer has the job(s): {', '.join(missing)}")
    kept = {k: jobs[k] for k in KEEP}
    for k in ("build-for-windows-flutter", "build-for-macOS", "build-rustdesk-android", "build-rustdesk-android-universal"):
        kept[k] = insert_stamp(k, kept[k])
    kept["build-for-macOS"], old_rename = mac_ad_hoc(kept["build-for-macOS"])
    kept["build-for-macOS"] = drop_rust_cache(kept["build-for-macOS"])
    body = "".join(kept.values())
    text = head + "\njobs:\n" + body
    if not text.endswith("\n"):
        text += "\n"
    text += "\n" + RELEASE_NOTES
    # the dmg that upstream uploads and publishes after the rename is named by DMG_FILE
    for old, new, n in EDITS:
        if new is None:
            continue
        got = text.count(old)
        if got != n:
            fail(f"edit not applied as expected ({got}x found, {n}x wanted): {old.strip()[:70]!r}")
        text = text.replace(old, new)
    # the remaining rust-cache steps (Windows, Android) only save on the default branch
    for anchor, n in (("          prefix-key: ${{ matrix.job.os }}\n", 1), ("          key: ${{ matrix.job.target }}\n", 1)):
        got = text.count(anchor)
        if got != n:
            fail(f"rust-cache anchor found {got}x, wanted {n}x: {anchor.strip()!r}")
        text = text.replace(anchor, anchor + RUST_CACHE_SAVE_IF)
    for job, key in VCPKG_TRIPLET_KEY.items():
        i = text.index(f"\n  {job}:\n")
        j = text.index("\n  ", i + 5)
        while not re.match(r"\n  [A-Za-z0-9_-]+:\n", text[j:j + 80]):
            j = text.index("\n  ", j + 3)
        body, anchor = text[i:j], "      - name: Install vcpkg dependencies\n"
        if body.count(anchor) != 1:
            fail(f"{job}: 'Install vcpkg dependencies' found {body.count(anchor)}x, wanted 1x")
        text = text[:i] + body.replace(anchor, VCPKG_CACHE.replace("@TRIPLET@", key) + anchor) + text[j:]
    for old, ins, n in INSERT_BEFORE:
        if ins is None:
            continue
        got = text.count(old)
        if got != n:
            fail(f"insertion point found {got}x, wanted {n}x: {old.strip()[:70]!r}")
        text = text.replace(old, ins + old)
    # the universal job has no matrix: its artifact name must not use matrix.job.arch
    i = text.index("  build-rustdesk-android-universal:")
    tail = text[i:]
    old = "name: ${{ env.APP_LOWER }}-${{ env.TAG_NAME }}-${{ matrix.job.arch }}.apk"
    if tail.count(old) != 1:
        fail(f"universal APK artifact name found {tail.count(old)}x, wanted 1x")
    text = text[:i] + tail.replace(old, "name: ${{ env.APP_LOWER }}-${{ env.TAG_NAME }}-universal.apk")
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file is not up to date")
    args = ap.parse_args()
    if not SRC.is_file():
        fail(f"{SRC} not found")
    text = generate(SRC.read_text(encoding="utf-8"))
    if args.check:
        same = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("magodesk-build.yml is up to date" if same else "magodesk-build.yml is OUT OF DATE: run make_workflow.py")
        sys.exit(0 if same else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines, {len(KEEP) + 1} jobs)")


if __name__ == "__main__":
    main()
